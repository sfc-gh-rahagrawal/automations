-- TABLE: CORE.DIM_TIME

CREATE TABLE IF NOT EXISTS DIM_TIME (
  DATE_KEY DATE NOT NULL,
  DAY_OF_MONTH NUMBER(38,0),
  DAY_OF_WEEK NUMBER(38,0),
  DAY_OF_YEAR NUMBER(38,0),
  DAY_NAME VARCHAR(10),
  DAY_NAME_SHORT VARCHAR(3),
  WEEK_OF_YEAR NUMBER(38,0),
  WEEK_START_DATE DATE,
  WEEK_END_DATE DATE,
  IS_WEEKEND BOOLEAN,
  MONTH_NUMBER NUMBER(38,0),
  MONTH_NAME VARCHAR(10),
  MONTH_NAME_SHORT VARCHAR(3),
  MONTH_START_DATE DATE,
  MONTH_END_DATE DATE,
  PRD_CDE VARCHAR(7),
  QUARTER_NUMBER NUMBER(38,0),
  QUARTER_NAME VARCHAR(6),
  QUARTER_START_DATE DATE,
  QUARTER_END_DATE DATE,
  YEAR_QUARTER VARCHAR(7),
  YEAR_NUMBER NUMBER(38,0),
  FISCAL_YEAR NUMBER(38,0),
  FISCAL_QUARTER NUMBER(38,0),
  IS_LEAP_YEAR BOOLEAN,
  IS_BUSINESS_DAY BOOLEAN,
  IS_HOLIDAY BOOLEAN,
  HOLIDAY_NAME VARCHAR(100),
  IS_CURRENT_DAY BOOLEAN,
  IS_CURRENT_WEEK BOOLEAN,
  IS_CURRENT_MONTH BOOLEAN,
  IS_CURRENT_QUARTER BOOLEAN,
  IS_CURRENT_YEAR BOOLEAN,
  SEASON VARCHAR(10),
  CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
  primary key (DATE_KEY)
);
